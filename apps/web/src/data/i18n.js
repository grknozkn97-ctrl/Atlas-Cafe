// Pick a language from the URL (?lang=it), then the saved choice, then the phone's language.
export function detectLang() {
  const codes = LANGS.map((l) => l.code);
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q && codes.includes(q)) return q;
  } catch { /* ignore */ }
  try {
    const saved = localStorage.getItem('atlas-lang');
    if (saved && codes.includes(saved)) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.toLowerCase());
  for (const l of nav) {
    if (/^(sr|me|cnr|hr|bs|sh)\b/.test(l)) return 'me';
    if (l.startsWith('it')) return 'it';
    if (l.startsWith('fr')) return 'fr';
    if (l.startsWith('tr')) return 'tr';
    if (l.startsWith('en')) return 'en';
  }
  return 'en';
}

export const euro = (n, lang) =>
  new Intl.NumberFormat(lang === 'en' ? 'en-IE' : lang === 'me' ? 'sr-Latn-ME' : lang, {
    style: 'currency', currency: 'EUR', minimumFractionDigits: 2,
  }).format(n);
